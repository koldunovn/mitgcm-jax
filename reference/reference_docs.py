def below10_section(variants, milestone):
    """Every compared check-list variable below 10 digits (admGrd of the code_ad builds excluded)."""
    out = [f"### {milestone}: compared variables below 10 digits", "", "| variant | variable | digits |",
           "|---|---|---:|"]
    for exp, inp, code in variants:
        ad = (exp, inp) in rr.AD_VARIANTS
        for r in rr.yardstick_rows(exp, inp):
            if r[0].startswith("forward list") or r[2] == 99 or r[2] >= 10 or (ad and r[1] == "admGrd"):
                continue
            out.append(f"| {_variant_label(exp, inp)} | {r[1]} | {r[2]} |")
    return out


def _digits_table(rows):
    out = ["| section | variable | grep pattern | digits | deciding | note |", "|---|---|---|---:|:---:|---|"]
    for section, name, d, dec, pat in rows:
        note = {16: "every printed digit equal", 22: "all values zero in both files", 99: "no comparison"}.get(d, "")
        out.append(f"| {section} | {name} | `{pat}` | {rr.fmt_digits(d)} | {'yes' if dec else ''} | {note} |")
    return out


def _variant_label(exp, inp):
    return f"{exp}/{inp}"


def yardstick_section(variants=None, heading="## Yardstick: our oracle's STDOUT vs `results/`"):
    lines = [heading, "",
             "| variant | runs (STDOUT) | deciding variable | its digits | lowest compared digits | not compared |",
             "|---|---|---|---:|---:|---|"]
    detail = []
    for exp, inp, code in rr.VARIANTS if variants is None else variants:
        rows = rr.yardstick_rows(exp, inp)
        main = [r for r in rows if not r[0].startswith("forward list")]
        dec = next((r for r in main if r[3]), None)
        ad = (exp, inp) in rr.AD_VARIANTS
        comp = [r[2] for r in main if r[2] != 99 and not (ad and r[1] == "admGrd")]
        nc = [r[1] for r in main if r[2] == 99]
        runs = "fdzero + yardstick" if ad else rr.find_run(exp, inp, "yardstick")["run_id"]
        lines.append(f"| {_variant_label(exp, inp)} | {runs} | {dec[1]} | {rr.fmt_digits(dec[2])} | "
                     f"{min(comp) if comp else '--'} | {' '.join(dict.fromkeys(nc)) or '-'} |")
        names = rr.checklist_names(exp, inp)
        detail += ["", f"### {_variant_label(exp, inp)}", "",
                   f"Check list ({len(names)} variables, testreport's listVar): {' '.join(names)}", ""]
        detail += _digits_table(rows)
        for name in dict.fromkeys(r[1] for r in main if r[2] == 99):
            why = NOT_COMPARED.get((exp, name))
            if why:
                detail.append(f"\n`{name}` not compared: {why}.")
    note = ["", "The lowest-digits column excludes admGrd of the forward-only code_ad builds (0 by construction, see "
            "the proposals). Every compared variable of the jaxdump runs (dumps off and on) and of the repeat runs has the "
            "same STDOUT numbers as the yardstick run (section 'Repeat and instrumented runs'; M2: the invisibility "
            "table)."]
    return lines + note + detail


def _first_numbers(res):
    """Short description of the numeric differences of a compare_runs result."""
    rec = res["records"]
    diff = [n for n in res["different"] if "only_in" not in rec[n]]
    only = [f"{n} only in {rec[n]['only_in']}" for n in res["different"] if "only_in" in rec[n]]
    return diff, only


