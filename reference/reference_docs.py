def m2_invisibility_section(variants=None, milestone="M2"):
    """Invisibility verdicts of the M2 (M3) triples (reference/jaxdump/invisibility.py files next to the runs)."""
    out = [f"## {milestone}: invisibility of the jaxdump shim (plain vs dumps off vs dumps on)", "",
           "| variant | job | verdict file | verdict |", "|---|---|---|---|"]
    for exp, inp, code in (rr.M2_VARIANTS if variants is None else variants):
        j = rr.M2_TRIPLE.get((exp, inp)) or rr.M3_TRIPLE.get((exp, inp)) or rr.M4_TRIPLE[(exp, inp)]
        f = rr.invisibility_file(exp, inp)
        text = f.read_text() if f.is_file() else ""
        lines = [ln for ln in text.split("\n") if ln.startswith(("INVISIBLE", "VISIBLE"))]
        verdict = "VISIBLE" if any(ln.startswith("VISIBLE") for ln in lines) else "INVISIBLE" if lines else "MISSING"
        ex = sorted({m for ln in lines for m in re.findall(r"(DIAGSTATS_UNSET_REGIONS [1-9]\d*)", ln)})
        note = f" ({', '.join(ex)})" if ex else ""
        out.append(f"| {_variant_label(exp, inp)} | {j} | {f.name} | {verdict}{note} |")
    if milestone != "M2":
        return out + ["", "Exemptions as in Task 4 and M2 (build stamps, timers, communication counters with the probe "
                      f"on, netCDF build stamps); no new exemption for {milestone}."]
    out += ["", "Exemptions as in Task 4 (build stamps, timers, communication counters with the probe on, netCDF build "
            "stamps), plus DIAGSTATS_UNSET_REGIONS (`reference/jaxdump/invisibility.py`): global_ocean.cs32x15/input "
            "writes the statistics-diagnostics file dynStDiag (mnc) with statGlob(.,.,j) of all 11 regions, but only "
            "region 0 is computed (no stat_region in data.diagnostics); regions 1-10 hold uninitialised values of a "
            "local array (diagstats_output.F:77-84, diagstats_mnc_out.F:255-257, 298-301), which differ between the "
            "plain and the instrumented binary. Region 0 and every other byte are identical."]
    return out


